"""Generate override files from verified Puppet branches or GitHub PRs."""

from __future__ import annotations

import getpass
import json
import re
import subprocess
from pathlib import Path

import click

from ..exceptions import UserError

UPSTREAM = "mozilla-platform-ops/ronin_puppet"


def _run(command: list[str]) -> subprocess.CompletedProcess[str]:
    try:
        return subprocess.run(command, capture_output=True, text=True, check=False, timeout=60)
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise UserError(f"Could not run {command[0]}: {exc}") from exc


def _quote(value: str) -> str:
    """Double quote shell values while preserving the existing override style."""
    for char in ("\\", '"', "$", "`"):
        value = value.replace(char, "\\" + char)
    return f'"{value}"'


def create_override(source: str, *, output: Path | None, output_dir: Path) -> Path:
    """Resolve a source, verify its branch, and exclusively create an override."""
    repo = f"https://github.com/{UPSTREAM}.git"
    branch = source
    pr_url = None
    title = None
    if source.isdecimal() or source.startswith(("https://", "http://")):
        command = ["gh", "pr", "view", source]
        if source.isdecimal():
            command.extend(["--repo", UPSTREAM])
        command.extend(
            [
                "--json",
                "number,title,headRefName,isCrossRepository,headRepositoryOwner,headRepository,url",
            ]
        )
        result = _run(command)
        if result.returncode:
            raise UserError(f"Failed to fetch PR: {source}: {result.stderr.strip()}")
        try:
            pr = json.loads(result.stdout)
            branch = pr["headRefName"]
            title = pr["title"]
            pr_url = pr["url"]
            number = int(pr["number"])
            if not all(isinstance(value, str) and value for value in (branch, title, pr_url)):
                raise ValueError("missing PR text fields")
            if pr["isCrossRepository"]:
                owner = pr["headRepositoryOwner"]["login"]
                name = pr["headRepository"]["name"]
                if not all(
                    isinstance(value, str) and re.fullmatch(r"[\w.-]+", value)
                    for value in (owner, name)
                ):
                    raise ValueError("invalid fork repository")
                repo = f"https://github.com/{owner}/{name}.git"
        except (ValueError, KeyError, TypeError) as exc:
            raise UserError(f"Invalid GitHub PR response: {exc}") from exc
        slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")[:50].rstrip("-")
        filename = f"pr-{number}-{slug}.override"
    else:
        filename = branch.replace("/", "_") + ".override"

    path = output if output is not None else output_dir / filename
    if path.exists() or path.is_symlink():
        raise UserError(f"Override file already exists: {path}")
    if _run(["git", "check-ref-format", f"refs/heads/{branch}"]).returncode:
        raise UserError(f"Invalid branch name: {branch}")
    result = _run(["git", "ls-remote", "--exit-code", "--heads", repo, f"refs/heads/{branch}"])
    if result.returncode:
        if result.returncode == 2:
            raise UserError(f"Branch not found: {branch} in {repo}")
        raise UserError(
            f"Failed to verify branch: {branch} in {repo} (git exit {result.returncode}); "
            f"check network access and repository permissions. {result.stderr.strip()}"
        )

    user = getpass.getuser()
    comments = [f"#   branch: {branch}", f"#   user: {user}"]
    if pr_url:
        comments.extend([f"#   pr: {pr_url}", f"#   title: {title}"])
    # Keep arbitrary PR titles in comments, including embedded newlines.
    comment_block = "\n".join(line.replace("\r", " ").replace("\n", "\n# ") for line in comments)
    repo_block = f"PUPPET_REPO={_quote(repo)}"
    if not pr_url:
        repo_block += f"\n# PUPPET_REPO={_quote(f'https://github.com/{user}/ronin_puppet.git')}"
    content = f"""# If you place this file at `/etc/puppet/ronin_settings`
# the `run-puppet.sh` script will use the values here.

# Override file autogenerated by fleetroll create-override for:
{comment_block}

# puppet overrides
{repo_block}
PUPPET_BRANCH={_quote(branch)}
PUPPET_MAIL={_quote(user + "@mozilla.com")}

# taskcluster overrides
# To change worker pools, set WORKER_TYPE_OVERRIDE to the target role's base
# worker type with your desired suffix appended (verify every target host).
# WORKER_TYPE_OVERRIDE=''
"""
    try:
        with path.open("x", encoding="utf-8") as file:
            file.write(content)
    except OSError as exc:
        raise UserError(f"Could not create override file {path}: {exc}") from exc
    click.echo(f"Verified branch: {branch} in {repo}")
    click.echo(f"Created override file: {path}")
    return path
